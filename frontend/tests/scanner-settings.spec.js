test('52W range saves and collapsing sections preserves entered values', async ({page},info)=>{
  let config={index_name:'NIFTY500',universe_mode:'index',ma_type:'SMMA',length:5,delay:0,offset_sigma:6,alma_offset:.85,pe_filter_operator:'none'}
  await page.route('**/api/scanner/config',r=>{if(r.request().method()==='POST')config=r.request().postDataJSON();return r.fulfill({json:config})})
  await page.request.post('/api/login',{data:{username:'fixture-user',password:'fixture-password'}})
  await page.goto('/')
  if(info.project.name==='mobile')await page.getByRole('button',{name:'Open navigation menu'}).click()
  await page.getByRole('button',{name:/Settings/}).click()
  await expandSettings(page)
  await page.getByLabel('Min distance from 52W high %').fill('10')
  await page.getByLabel('Max distance from 52W high %').fill('20')
  const summary=page.locator('summary').filter({hasText:'Fundamental filters'})
  await summary.click()
  await expect(page.getByLabel('Min distance from 52W high %')).toBeHidden()
  await page.getByRole('button',{name:'Save settings'}).click()
  await expect.poll(()=>config.min_52w_high_distance_pct).toBe(10)
  expect(config.max_52w_high_distance_pct).toBe(20)
  await summary.focus()
  await page.keyboard.press('Enter')
  await expect(page.getByLabel('Min distance from 52W high %')).toHaveValue('10')
  await page.getByLabel('Min distance from 52W high %').fill('')
  await page.getByRole('button',{name:'Save settings'}).click()
  await expect.poll(()=>config.min_52w_high_distance_pct).toBeNull()
  await page.screenshot({path:info.outputPath('expandable-settings.png'),fullPage:true})
})

async function expandSettings(page) {
  const sections = page.locator('.settings-disclosure')
  await expect(sections).toHaveCount(6)
  await expect(page.locator('.settings-disclosure[open]')).toHaveCount(0)
  for (const summary of await page.locator('.settings-disclosure > summary').all()) await summary.click()
}
