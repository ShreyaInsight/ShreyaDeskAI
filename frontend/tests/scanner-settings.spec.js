import { test, expect } from '@playwright/test'
test('universe choice preserves index and volume fields save and clear independently', async ({ page }, info) => {
  let saved = { index_name:'NIFTY500', universe_mode:'index', ma_type:'SMMA', length:5, delay:0, offset_sigma:6, alma_offset:.85, pe_filter_operator:'none', volume_min:null, volume_max:null }
  await page.route('**/api/session', route => route.fulfill({ json:{ connected:true } }))
  await page.route('**/api/scanner/config', async route => {
    if (route.request().method() === 'POST') saved = route.request().postDataJSON()
    await route.fulfill({ json:saved })
  })
  await page.request.post('/api/login',{data:{username:'fixture-user',password:'fixture-password'}})
 await page.goto('/')
  if (info.project.name === 'mobile') await page.getByRole('button',{name:'Open navigation menu'}).click()
  await page.getByRole('button',{name: /Settings/}).click()
  await expandSettings(page)
  const index = page.getByLabel('Market index')
  await expect(index).toHaveValue('NIFTY500')
  await page.getByRole('button',{name:'Full NSE',exact:true}).click()
  await expect(index).toHaveCount(0)
  await page.getByLabel('Exclude volume below').fill('1000')
  await page.getByLabel('Exclude volume above').fill('5000')
  await page.getByLabel("Today's volume > 30-day average volume").check()
  await page.getByRole('button',{name:'Save settings'}).click()
  await expect(page.getByText('Settings saved')).toBeVisible()
  expect(saved.universe_mode).toBe('full_nse');expect(saved.index_name).toBe('NIFTY500')
  expect(saved.volume_min).toBe(1000);expect(saved.volume_max).toBe(5000);expect(saved.volume_above_30d_average).toBe(true)
  await page.getByRole('button',{name:'Index',exact:true}).click()
  await expect(index).toHaveValue('NIFTY500')
  await page.getByLabel('Exclude volume below').fill('')
  await page.getByRole('button',{name:'Save settings'}).click()
  await expect.poll(()=>saved.volume_min).toBeNull()
  expect(saved.volume_max).toBe(5000)
})

